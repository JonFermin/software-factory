"""Windows Task Scheduler backend (``schtasks``).

``/TR`` is limited to 261 characters and quoting through schtasks is fragile, so each job is a
generated ``.cmd`` wrapper in ``paths.scripts`` that ``cd``s to the repo, sets env, runs the
``uv run ... factory`` command and appends stdout/stderr to ``logs/scheduler.log``. Tasks are
created with ``/RL LIMITED`` and *without* ``/RU``/``/NP`` so they keep the default "run only when
the user is logged on" (interactive token), which is what lets desktop toasts appear.

``schtasks /Create`` has no switch for the power conditions and defaults to "do not start on
batteries, stop when going on batteries", which means a laptop on battery never ticks and
unplugging mid-tick kills the running worker. After each ``/Create`` the task's settings are
therefore rewritten with ``Set-ScheduledTask`` (Windows PowerShell, always present) to allow both.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import TYPE_CHECKING

from . import JOBS, JobName, RunResult, ScheduleReport, SchedulerError, Weekday

if TYPE_CHECKING:
    from collections.abc import Sequence

    from . import Runner, ScheduleSpec

WEEKDAYS: tuple[Weekday, ...] = ("MON", "TUE", "WED", "THU", "FRI", "SAT", "SUN")
TASKRUN_MAX_LEN = 261  # documented schtasks /TR limit (the reason wrappers exist)
WRAPPER_SUFFIX = ".cmd"
POWERSHELL = "powershell"  # Windows PowerShell 5.1 ships with Windows; pwsh may not be installed
EXECUTION_TIME_LIMIT_HOURS = 6  # a tick that runs this long is stuck (workers time out after 30 min)
# cmd.exe metacharacters / whitespace that force double quotes around an argument.
_NEEDS_QUOTES = set(' \t&()^<>|;,=')
# Substrings (lower-case) that mean "no such task" in schtasks output (English locale).
NOT_FOUND_MARKERS = ("cannot find the file specified", "does not exist", "no such")
_SET_LINE = re.compile(r'^set "(?P<key>[^=]+)=(?P<value>.*)"$')


def cmd_quote(arg: str) -> str:
    """Quote one argument for a ``.cmd`` line. Windows paths cannot contain ``"`` so no escaping."""
    if arg == "" or any(ch in _NEEDS_QUOTES for ch in arg):
        return f'"{arg}"'
    return arg


def ps_quote(text: str) -> str:
    """A PowerShell single-quoted literal (only ``'`` needs doubling)."""
    return "'" + text.replace("'", "''") + "'"


def wrapper_path(spec: ScheduleSpec, job: JobName) -> Path:
    return spec.scripts_dir / f"{spec.task_name(job)}{WRAPPER_SUFFIX}"


def wrapper_env(path: Path) -> dict[str, str]:
    """The ``set "KEY=VALUE"`` lines of a generated wrapper (what the scheduled job will see)."""
    env: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        match = _SET_LINE.match(line.strip())
        if match:
            env[match["key"]] = match["value"]
    return env


# ------------------------------------------------------------------------------ render
def render_wrapper_cmd(
    *,
    repo_root: Path,
    argv: Sequence[str],
    env: dict[str, str],
    log_path: Path,
    job: str = "",
) -> str:
    """Text of the ``.cmd`` wrapper (CRLF line endings)."""
    log = cmd_quote(str(log_path))
    log_dir = cmd_quote(str(log_path.parent))
    lines = [
        "@echo off",
        "rem Generated by `factory schedule install`; do not edit, re-run install instead.",
        f"cd /d {cmd_quote(str(repo_root))}",
        *[f'set "{key}={value}"' for key, value in env.items()],
        f"if not exist {log_dir} mkdir {log_dir}",
        f"echo [%DATE% %TIME%] {job or 'job'} start>> {log}",
        f"{' '.join(cmd_quote(a) for a in argv)} >> {log} 2>&1",
        "exit /b %ERRORLEVEL%",
    ]
    return "\r\n".join(lines) + "\r\n"


def _taskrun(wrapper: Path) -> str:
    # Embedded quotes survive subprocess's list2cmdline, so the stored action is the quoted path.
    taskrun = f'"{wrapper}"'
    if len(taskrun) > TASKRUN_MAX_LEN:
        raise SchedulerError(f"wrapper path exceeds schtasks /TR limit ({TASKRUN_MAX_LEN}): {wrapper}")
    return taskrun


def render_schtasks_create(task_name: str, wrapper_path: Path, interval_minutes: int) -> list[str]:
    """``schtasks /Create`` argv for the tick job (every N minutes)."""
    if not 1 <= interval_minutes <= 1439:
        raise SchedulerError(f"schtasks /SC MINUTE /MO must be 1..1439, got {interval_minutes}")
    return [
        "schtasks", "/Create",
        "/TN", task_name,
        "/SC", "MINUTE", "/MO", str(interval_minutes),
        "/TR", _taskrun(wrapper_path),
        "/RL", "LIMITED",
        "/F",
    ]  # fmt: skip


def render_schtasks_create_weekly(
    task_name: str, wrapper_path: Path, weekday: Weekday = "MON", start_time: str = "09:00"
) -> list[str]:
    """``schtasks /Create`` argv for the weekly digest job."""
    if weekday not in WEEKDAYS:
        raise SchedulerError(f"weekday must be one of {WEEKDAYS}, got {weekday!r}")
    return [
        "schtasks", "/Create",
        "/TN", task_name,
        "/SC", "WEEKLY", "/D", weekday, "/ST", start_time,
        "/TR", _taskrun(wrapper_path),
        "/RL", "LIMITED",
        "/F",
    ]  # fmt: skip


def render_power_settings(task_name: str) -> list[str]:
    """``powershell`` argv that lets the task start on battery and keeps it running when the machine
    switches to battery (plus a cap on a runaway run; ``IgnoreNew`` is the schtasks default too)."""
    command = (
        f"Set-ScheduledTask -TaskName {ps_quote(task_name)} -Settings (New-ScheduledTaskSettingsSet "
        "-AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew "
        f"-ExecutionTimeLimit (New-TimeSpan -Hours {EXECUTION_TIME_LIMIT_HOURS}))"
    )
    return [POWERSHELL, "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-Command", command]


def render_schtasks_delete(task_name: str) -> list[str]:
    return ["schtasks", "/Delete", "/TN", task_name, "/F"]


def render_schtasks_query(task_name: str) -> list[str]:
    return ["schtasks", "/Query", "/TN", task_name, "/FO", "LIST", "/V"]


def is_not_found(result: RunResult) -> bool:
    text = result.output.lower()
    return not result.ok and any(marker in text for marker in NOT_FOUND_MARKERS)


# ------------------------------------------------------------------------------ actions
def _create_argv(spec: ScheduleSpec, job: JobName, wrapper: Path) -> list[str]:
    if job == "tick":
        return render_schtasks_create(spec.task_name(job), wrapper, spec.interval_minutes)
    return render_schtasks_create_weekly(spec.task_name(job), wrapper, spec.digest_weekday, spec.digest_time)


def install(spec: ScheduleSpec, runner: Runner) -> ScheduleReport:
    report = ScheduleReport(os="windows", profile=spec.profile, action="install")
    spec.scripts_dir.mkdir(parents=True, exist_ok=True)
    spec.logs_dir.mkdir(parents=True, exist_ok=True)
    for job in spec.jobs:
        wrapper = wrapper_path(spec, job)
        text = render_wrapper_cmd(
            repo_root=spec.repo_root, argv=spec.argv(job), env=spec.env(), log_path=spec.log_path, job=job
        )
        wrapper.write_text(text, encoding="utf-8", newline="")  # keep CRLF as rendered
        report.files.append(wrapper)
        argv = _create_argv(spec, job, wrapper)
        report.commands.append(argv)
        result = runner(argv)
        if not result.ok:
            raise SchedulerError(f"schtasks /Create {spec.task_name(job)} failed ({result.returncode}): {result.output}")
        report.jobs.append(spec.task_name(job))
        _allow_on_battery(spec.task_name(job), runner, report)
    return report


def _allow_on_battery(task_name: str, runner: Runner, report: ScheduleReport) -> None:
    """Rewrite the task's power settings; a failure is a note (the task still runs on AC) that
    ``doctor`` keeps reporting while the query output shows the schtasks default."""
    argv = render_power_settings(task_name)
    report.commands.append(argv)
    try:
        result = runner(argv)
        problem = "" if result.ok else (result.output.strip().splitlines() or [f"exit {result.returncode}"])[0]
    except SchedulerError as exc:
        problem = str(exc)
    if problem:
        report.notes.append(
            f"{task_name}: could not allow running on battery ({problem}); the task keeps the schtasks "
            "default (no start on battery, stop when going on battery)"
        )


def uninstall(spec: ScheduleSpec, runner: Runner) -> ScheduleReport:
    """Delete both tasks (a missing task is not an error) and remove the wrappers."""
    report = ScheduleReport(os="windows", profile=spec.profile, action="uninstall")
    for job in JOBS:
        name = spec.task_name(job)
        argv = render_schtasks_delete(name)
        report.commands.append(argv)
        result = runner(argv)
        if result.ok:
            report.jobs.append(name)
        elif is_not_found(result):
            report.notes.append(f"{name}: not installed")
        else:
            raise SchedulerError(f"schtasks /Delete {name} failed ({result.returncode}): {result.output}")
        wrapper = wrapper_path(spec, job)
        if wrapper.exists():
            wrapper.unlink()
            report.files.append(wrapper)
    return report


def show(spec: ScheduleSpec, runner: Runner) -> str:
    """The ``schtasks /Query /V`` listing per job, plus the env the wrapper under the current
    ``scripts`` dir sets (the query shows the wrapper path but not what it exports)."""
    sections: list[str] = []
    for job in JOBS:
        name = spec.task_name(job)
        result = runner(render_schtasks_query(name))
        if result.ok:
            wrapper = wrapper_path(spec, job)
            if wrapper.is_file():
                env = ", ".join(f"{k}={v}" for k, v in wrapper_env(wrapper).items()) or "(none)"
                extra = f"Wrapper:                              {wrapper}\nWrapper Env:                          {env}"
            else:
                # Deliberately no path here: install_drift looks for the current data dir in this text.
                extra = (
                    "Wrapper:                              missing (no wrapper for this task under the current "
                    "data dir; installed from another SOFTWARE_FACTORY_DATA_DIR?)"
                )
            sections.append(result.stdout.strip() + "\n" + extra)
        elif is_not_found(result):
            sections.append(f"{name}: not installed")
        else:
            sections.append(f"{name}: error ({result.returncode}): {result.output}")
    return "\n\n".join(sections)
